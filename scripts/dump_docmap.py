"""Document-map summary for every DEV document (P3, Part E) -> logs/P3_docmaps.md.

Per document: blocks per kind, pages / sheets, flag counts (flag names only), characters per
token class and the estimated prompt tokens with the P3-18 ratios. No block text, no cell
value, no address (D04, R31). Held-out documents are refused.

    uv run python scripts/dump_docmap.py [--docs rentroll_001 ...]
"""

from __future__ import annotations

import argparse
import math
import sys
import time
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from make_outputs import DOCS, ROOT, manifest

from app.llm.models import ModelCatalog
from app.readers import read_document

HELD_OUT = frozenset({"lease_003", "budget_001"})  # D03
REPORT = ROOT / "logs" / "P3_docmaps.md"


def summarise(doc_id: str, row: dict[str, str], est) -> dict:
    path = DOCS / row["file"]
    t0 = time.monotonic()
    dm = read_document(path.suffix.lower().lstrip("."), path.read_bytes())
    secs = time.monotonic() - t0
    kinds = Counter(b.kind for b in dm.blocks)
    flags = Counter(f.split("=", 1)[0] for b in dm.blocks for f in b.flags)
    chars: Counter = Counter()
    images = 0
    for b in dm.blocks:
        if b.kind == "image":
            images += 1
        else:
            chars[b.token_class] += len(b.render()) + 1
    tokens = sum(math.ceil(n / est.ratio(c)) for c, n in chars.items())
    pages = sorted({b.page for b in dm.blocks if b.page is not None})
    sheets = {b.address.split("!", 1)[0] for b in dm.blocks if "!" in b.address}
    meta = {k: v for k, v in dm.meta.items() if isinstance(v, int | str | type(None))}
    return {
        "doc": doc_id,
        "type": dm.file_type,
        "blocks": len(dm.blocks),
        "kinds": dict(sorted(kinds.items())),
        "pages": len(pages),
        "sheets": len(sheets),
        "tables": kinds.get("table_row", 0),
        "flags": dict(sorted(flags.items())),
        "chars": dict(sorted(chars.items())),
        "images": images,
        "tokens_est": tokens + images * est.image_tokens,
        "meta": meta,
        "secs": secs,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--docs", nargs="+")
    args = ap.parse_args()
    rows = manifest()
    docs = args.docs or [d for d in rows if d not in HELD_OUT]
    if any(d in HELD_OUT for d in docs):
        print("refused: held-out documents are sealed (D03)")
        return 2
    est = ModelCatalog.load().estimate
    recs = [summarise(d, rows[d], est) for d in docs]
    lines = [
        "# P3 document maps (DEV)",
        "",
        "Generated by `scripts/dump_docmap.py`. Counts only: no block text, values or "
        "addresses. Token estimate = block characters / chars-per-token of the block's class "
        f"(row {est.ratio('row')}, prose {est.ratio('prose')}; P3-18) + "
        f"{est.image_tokens} per image, before the margin and prompt overhead.",
        "",
        "| doc | type | blocks | kinds | pages | sheets | table rows | images | "
        "chars by class | est. tokens | read s |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in recs:
        kinds = ", ".join(f"{k} {v}" for k, v in r["kinds"].items())
        chars = ", ".join(f"{k} {v}" for k, v in r["chars"].items()) or "-"
        lines.append(
            f"| {r['doc']} | {r['type']} | {r['blocks']} | {kinds} | {r['pages'] or '-'} | "
            f"{r['sheets'] or '-'} | {r['tables']} | {r['images']} | {chars} | "
            f"{r['tokens_est']} | {r['secs']:.1f} |"
        )
    lines += ["", "## Flags (blocks carrying each flag) and reader facts", ""]
    for r in recs:
        flags = ", ".join(f"{k} {v}" for k, v in r["flags"].items()) or "none"
        meta = ", ".join(f"{k}={v}" for k, v in r["meta"].items()) or "-"
        lines.append(f"- **{r['doc']}**: flags: {flags}. Reader: {meta}.")
    REPORT.parent.mkdir(exist_ok=True)
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    for r in recs:
        print(
            f"{r['doc']:14s} {r['type']:4s} blocks={r['blocks']} kinds={r['kinds']} "
            f"images={r['images']} tokens_est={r['tokens_est']} {r['secs']:.1f}s"
        )
    print(f"wrote {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
